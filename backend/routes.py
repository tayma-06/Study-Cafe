from fastapi import APIRouter, HTTPException

from models import get_all_users, get_user_by_id
from schemas import UserResponse

router = APIRouter()


@router.get("/users", response_model=list[UserResponse])
def get_users():
    users = get_all_users()

    return [
        {
            "user_id": user[0],
            "name": user[1],
            "email": user[2],
            "role": user[3],
            "created_at": user[4],
        }
        for user in users
    ]


@router.get("/users/{user_id}", response_model=UserResponse)
def get_user(user_id: int):
    user = get_user_by_id(user_id)

    if user is None:
        raise HTTPException(
            status_code=404,
            detail="User not found"
        )

    return {
        "user_id": user[0],
        "name": user[1],
        "email": user[2],
        "role": user[3],
        "created_at": user[4],
    }